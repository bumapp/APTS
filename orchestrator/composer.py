@chat_app.get("/api/report/{eid}")
def download_report(eid: str, fmt: str = "md") -> FileResponse:
    """Serve the Adviser's report file for download (md or json)."""
    u = _as_uuid(eid)
    if u is None:
        raise HTTPException(400, "invalid engagement id")
    ext = "json" if fmt == "json" else "md"
    path = os.path.join(REPORTS_DIR, f"report-{u}.{ext}")
    if not os.path.exists(path):
        raise HTTPException(404, "report not available yet (has Reporting finished?)")
    media = "application/json" if ext == "json" else "text/markdown; charset=utf-8"
    return FileResponse(path, media_type=media, filename=f"apts-report-{u}.{ext}")


@chat_app.post("/api/engagement/{eid}/delete")
def delete_engagement(eid: str) -> dict:
    """Delete an engagement and its stored artifacts (cascades). Best-effort: a
    stage still executing may error on its next store write, which is contained."""
    u = _as_uuid(eid)
    if u is None:
        raise HTTPException(400, "invalid engagement id")
    with get_conn() as conn, conn.cursor() as cur:
        cur.execute("DELETE FROM engagements WHERE id = %s RETURNING id", (str(u),))
        deleted = cur.fetchone() is not None
    return {"ok": deleted, "engagement_id": str(u)}


