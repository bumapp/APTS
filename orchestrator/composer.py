"""The Composer — APTS's conversational front, plus the Chat UI that talks to it.

Runs as a fourth server inside the orchestrator container (a FastAPI app on
:8090, published to the host). The browser loads a small single-page chat from
``/`` and opens a WebSocket to ``/ws``; the user talks only to the Composer, and
the Composer drives the pipeline through the native-MCP control tools
(``orchestrator.mcp_control`` on :9100) — create, status, stop, artifacts.

The Composer is a genuine tool-driving loop over the hosted model (it reuses the
agents' ``agentic`` plumbing for auth/canonicalisation, since the orchestrator
image ships the agent code). It collects and validates the engagement parameters
in conversation, creates the engagement only when it has them, and answers
status/stop/artifact requests. Per-step directives to each agent are still
generated by the orchestrator's driven advancement; the Composer owns the
human-facing conversation and the start of the run.

The side panel tracks EVERY engagement — the ones started this session and the
recent ones already in the store — each as its own collapsible card with a live
pipeline, a report download, and a delete. Live progress is not pushed from the
agents into this app (they report to the public :8443 server, a different
app/loop); instead one poller per engagement reads the shared store and streams
each stage transition to the browser, tagged with its engagement id.
"""
