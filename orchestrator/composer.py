def _arg_summary(name: str, args: dict) -> str:
    if not args:
        return name + "()"
    inner = ", ".join(f"{k}={json.dumps(v, default=str)}" for k, v in args.items())
    return f"{name}({inner})"[:200]


def _sanitize_ai(ai) -> None:
    """Strip tool calls with unparseable-JSON arguments from an AIMessage, in place.

    A model can emit a tool call whose ``arguments`` are not valid JSON. The client
    keeps it in ``invalid_tool_calls`` AND in ``additional_kwargs['tool_calls']`` (the
    raw block ChatOpenAI actually re-serializes on the next request) — so clearing only
    the parsed field is not enough; re-sending still 400s the Bedrock gateway with
    'Expecting property name enclosed in double quotes'. Clean BOTH; keep valid calls."""
    try:
        if getattr(ai, "invalid_tool_calls", None):
            ai.invalid_tool_calls = []
        raw = (getattr(ai, "additional_kwargs", None) or {}).get("tool_calls")
        if raw:
            good = []
            for tc in raw:
                args = ((tc or {}).get("function") or {}).get("arguments", "")
                try:
                    json.loads(args or "{}")
                    good.append(tc)
                except Exception:  # noqa: BLE001 — drop the malformed call
                    pass
            if good:
                ai.additional_kwargs["tool_calls"] = good
            else:
                ai.additional_kwargs.pop("tool_calls", None)
    except Exception:  # noqa: BLE001 — sanitising must never crash the turn
        pass


def _scrub(messages: list) -> None:
    """Remove malformed tool-call remnants (in place) that poison re-sends to the model,
    plus any tool result orphaned by their removal."""
    valid_ids: set = set()
    kept: list = []
    for msg in messages:
        _sanitize_ai(msg)
        for tc in (getattr(msg, "tool_calls", None) or []):
            valid_ids.add(tc.get("id"))
        tcid = getattr(msg, "tool_call_id", None)
        if tcid is not None and tcid not in valid_ids:
            continue  # tool result whose call was dropped — would dangle
        kept.append(msg)
    messages[:] = kept


@chat_app.websocket("/ws")
async def ws(websocket: WebSocket) -> None:
    await websocket.accept()
    send_lock = asyncio.Lock()

    async def send(obj: dict) -> None:
        async with send_lock:
            await websocket.send_json(obj)

    messages: list = [agentic.SystemMessage(content=SYSTEM_PROMPT)]
    pollers: dict[str, asyncio.Task] = {}

    async def poll_progress(eid: str) -> None:
        """Stream each stage transition for one engagement to the browser."""
        u = _as_uuid(eid)
        prev: dict[str, str] = {}
        loot_sent = False
        while True:
            st = await asyncio.to_thread(_status, u)
            if not st:
                await send({"type": "gone", "engagement_id": eid})
                return
            for agent, info in st["per_agent"].items():
                s = info.get("status", "pending")
                if prev.get(agent) != s:
                    prev[agent] = s
                    await send({"type": "progress", "engagement_id": eid,
                                "agent": agent, "label": STAGE_LABEL.get(agent, agent),
                                "status": s})
                    # When exploitation finishes, surface any loot it collected.
                    if agent == "exploit" and s in ("done", "completed") and not loot_sent:
                        loot_sent = True
                        loot = await asyncio.to_thread(_exploit_loot, eid)
                        if loot:
                            summary = await _summarise_loot(loot)
                            await send({"type": "loot", "engagement_id": eid,
                                        "summary": summary, "items": loot[:40]})
            if st["status"] in ("complete", "failed", "cancelled"):
                await send({"type": "engagement", "engagement_id": eid,
                            "status": st["status"]})
                return
            await asyncio.sleep(2)

    async def ensure_engagement(eid: str, target_url: str | None = None,
                                status: str | None = None,
                                fresh: bool = False) -> None:
        """Announce an engagement to the UI and start polling it (once).

        ``fresh`` marks the one just started this session, so the UI opens it and
        collapses the rest; engagements loaded from history arrive collapsed."""
        if eid in pollers:
            return
        if target_url is None:
            st = await asyncio.to_thread(_status, _as_uuid(eid))
            target_url = (st or {}).get("target_url")
            status = (st or {}).get("status")
        await send({"type": "engagement_new", "engagement_id": eid,
                    "target_url": target_url or "?", "status": status or "running",
                    "fresh": fresh})
        pollers[eid] = asyncio.create_task(poll_progress(eid))

    async def run_turn(text: str, mcp_client: Client, model) -> None:
        messages.append(agentic.HumanMessage(content=text))
        for _ in range(MAX_STEPS):
            try:
                ai = await model.ainvoke(messages, config=run_config(agent="orchestrator"))
            except Exception:  # noqa: BLE001
                # A malformed tool call in the history poisons every re-send (Bedrock
                # 400). Scrub it out and retry once before giving up.
                _scrub(messages)
                try:
                    ai = await model.ainvoke(messages, config=run_config(agent="orchestrator"))
                except Exception as exc2:  # noqa: BLE001 — surface the failure to the UI
                    await send({"type": "error", "text": f"model call failed: {str(exc2)[:200]}"})
                    return
            # Never store a malformed tool call — it would poison the next turn's
            # re-send (both the parsed field and the raw additional_kwargs block).
            had_invalid = bool(getattr(ai, "invalid_tool_calls", None))
            _sanitize_ai(ai)
            messages.append(ai)
            calls = ai.tool_calls or []
            if not calls:
                txt = agentic.message_text(ai)
                if not txt and had_invalid:
                    # The model tried a tool call but garbled its JSON args; nudge it to
                    # retry (otherwise the user just sees "(no reply)").
                    messages.append(agentic.HumanMessage(content=(
                        "(system: your previous tool call had invalid JSON arguments and "
                        "was dropped — call the tool again with valid JSON, or reply "
                        "directly)")))
                    continue
                await send({"type": "assistant", "text": txt or "(no reply)"})
                return
            for call in calls:
                name = call["name"]
                args = call.get("args") or {}
                await send({"type": "tool", "text": _arg_summary(name, args)})
                out = await mcp_client.call_tool(name, args)
                payload = out.structured_content or {
                    "content": [getattr(b, "text", str(b)) for b in out.content]}
                if name == "create_engagement" and isinstance(payload, dict) \
                        and payload.get("engagement_id"):
                    await ensure_engagement(payload["engagement_id"],
                                            args.get("target_url"), "running",
                                            fresh=True)
                messages.append(agentic.ToolMessage(
                    content=json.dumps(payload, default=str)[:4000],
                    tool_call_id=call["id"]))

    try:
        async with Client(CONTROL_URL) as mcp_client:
            tools = (await mcp_client.list_tools()).tools
            # The model only needs the tool SCHEMAS (bind_tools); the Composer
            # dispatches each call itself below so it can emit UI events and run
            # the create_engagement side effect.
            lc_tools = agentic.as_langchain_tools(mcp_client, tools)
            model = build_chat_model("orchestrator").bind_tools(lc_tools)
            await send({"type": "assistant", "text": GREETING, "greeting": True})
            # Populate the side panel with recent engagements (finished pollers
            # do a single pass and exit; running ones stay live).
            for eid, target, status in await asyncio.to_thread(
                    _recent_engagements, RECENT_LIMIT):
                await ensure_engagement(eid, target, status)
            while True:
                raw = await websocket.receive_json()
                text = (raw.get("text") or "").strip()
                if not text:
                    continue
                await run_turn(text, mcp_client, model)
    except WebSocketDisconnect:
        pass
    except Exception as exc:  # noqa: BLE001 — keep one bad socket from taking the server
        log.warning("composer ws error: %s", exc)
    finally:
        for task in pollers.values():
            task.cancel()


def serve(port: int | None = None) -> None:
    """Run the Composer + Chat UI server. Called in a daemon thread from main."""
    port = port or int(os.environ.get("APTS_COMPOSER_PORT", "8090"))
    log.info("composer + chat UI on :%d (control MCP at %s)", port, CONTROL_URL)
    uvicorn.run(chat_app, host="0.0.0.0", port=port, log_config=None)


