def _arg_summary(name: str, args: dict) -> str:
    if not args:
        return name + "()"
    inner = ", ".join(f"{k}={json.dumps(v, default=str)}" for k, v in args.items())
    return f"{name}({inner})"[:200]


@chat_app.websocket("/ws")
async def ws(websocket: WebSocket) -> None:
    await websocket.accept()
    send_lock = asyncio.Lock()

    async def send(obj: dict) -> None:
        async with send_lock:
            await websocket.send_json(obj)

    messages: list[dict] = [{"role": "system", "content": SYSTEM_PROMPT}]
    pollers: dict[str, asyncio.Task] = {}
    llm = httpx.AsyncClient(timeout=agentic.LLM_TIMEOUT)

    async def poll_progress(eid: str) -> None:
        """Stream each stage transition for one engagement to the browser."""
        u = _as_uuid(eid)
        prev: dict[str, str] = {}
        loot_sent = False
        while True:
            st = await asyncio.to_thread(_status, u)
            if not st:
                await send({"type": "gone", "engagement_id": eid})
                return
            for agent, info in st["per_agent"].items():
                s = info.get("status", "pending")
                if prev.get(agent) != s:
                    prev[agent] = s
                    await send({"type": "progress", "engagement_id": eid,
                                "agent": agent, "label": STAGE_LABEL.get(agent, agent),
                                "status": s})
                    # When exploitation finishes, surface any loot it collected.
                    if agent == "exploit" and s in ("done", "completed") and not loot_sent:
                        loot_sent = True
                        loot = await asyncio.to_thread(_exploit_loot, eid)
                        if loot:
                            summary = await _summarise_loot(llm, loot)
                            await send({"type": "loot", "engagement_id": eid,
                                        "summary": summary, "items": loot[:40]})
            if st["status"] in ("complete", "failed", "cancelled"):
                await send({"type": "engagement", "engagement_id": eid,
                            "status": st["status"]})
                return
            await asyncio.sleep(2)

    async def ensure_engagement(eid: str, target_url: str | None = None,
                                status: str | None = None,
                                fresh: bool = False) -> None:
        """Announce an engagement to the UI and start polling it (once).

        ``fresh`` marks the one just started this session, so the UI opens it and
        collapses the rest; engagements loaded from history arrive collapsed."""
        if eid in pollers:
            return
        if target_url is None:
            st = await asyncio.to_thread(_status, _as_uuid(eid))
            target_url = (st or {}).get("target_url")
            status = (st or {}).get("status")
        await send({"type": "engagement_new", "engagement_id": eid,
                    "target_url": target_url or "?", "status": status or "running",
                    "fresh": fresh})
        pollers[eid] = asyncio.create_task(poll_progress(eid))

    async def run_turn(text: str, mcp_client: Client, openai_tools: list[dict]) -> None:
        messages.append({"role": "user", "content": text})
        for _ in range(MAX_STEPS):
            try:
                msg = await agentic.chat(llm, messages, tools=openai_tools)
            except httpx.HTTPError as exc:
                await send({"type": "error",
                            "text": f"model call failed: {agentic.err_body(exc)[:200] or exc}"})
                return
            messages.append(msg)
            calls = msg.get("tool_calls")
            if not calls:
                await send({"type": "assistant",
                            "text": (msg.get("content") or "").strip() or "(no reply)"})
                return
            for call in calls:
                name = call["function"]["name"]
                try:
                    args = json.loads(call["function"].get("arguments") or "{}")
                except json.JSONDecodeError:
                    args = {}
                await send({"type": "tool", "text": _arg_summary(name, args)})
                out = await mcp_client.call_tool(name, args)
                payload = out.structured_content or {
                    "content": [getattr(b, "text", str(b)) for b in out.content]}
                if name == "create_engagement" and isinstance(payload, dict) \
                        and payload.get("engagement_id"):
                    await ensure_engagement(payload["engagement_id"],
                                            args.get("target_url"), "running",
                                            fresh=True)
                messages.append({"role": "tool", "tool_call_id": call["id"],
                                 "content": json.dumps(payload, default=str)[:4000]})

    try:
        async with Client(CONTROL_URL) as mcp_client:
            tools = (await mcp_client.list_tools()).tools
            openai_tools = agentic.mcp_tools_to_openai(tools)
            await send({"type": "assistant", "text": GREETING, "greeting": True})
            # Populate the side panel with recent engagements (finished pollers
            # do a single pass and exit; running ones stay live).
            for eid, target, status in await asyncio.to_thread(
                    _recent_engagements, RECENT_LIMIT):
                await ensure_engagement(eid, target, status)
            while True:
                raw = await websocket.receive_json()
                text = (raw.get("text") or "").strip()
                if not text:
                    continue
                await run_turn(text, mcp_client, openai_tools)
    except WebSocketDisconnect:
        pass
    except Exception as exc:  # noqa: BLE001 — keep one bad socket from taking the server
        log.warning("composer ws error: %s", exc)
    finally:
        for task in pollers.values():
            task.cancel()
        await llm.aclose()


def serve(port: int | None = None) -> None:
    """Run the Composer + Chat UI server. Called in a daemon thread from main."""
    port = port or int(os.environ.get("APTS_COMPOSER_PORT", "8090"))
    log.info("composer + chat UI on :%d (control MCP at %s)", port, CONTROL_URL)
    uvicorn.run(chat_app, host="0.0.0.0", port=port, log_config=None)


